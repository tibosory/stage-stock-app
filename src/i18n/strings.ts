/** Placeholders in strings : `{nom}` ou `{{nom}}`. */
export type TranslateVars = Record<string, string | number | undefined | null>;

export function applyTemplate(template: string, vars?: TranslateVars): string {
  if (!vars) return template;
  let out = template;
  for (const [k, raw] of Object.entries(vars)) {
    const val = raw === undefined || raw === null ? '' : String(raw);
    let guard = 0;
    while (out.includes(`{${k}}`) && guard++ < 100) {
      out = out.split(`{${k}}`).join(val);
    }
    guard = 0;
    while (out.includes(`{{${k}}}`) && guard++ < 100) {
      out = out.split(`{{${k}}}`).join(val);
    }
  }
  return out;
}

export function tForLanguage(lang: AppLanguage, key: string, vars?: TranslateVars): string {
  const dict = dictionaries[lang] ?? fr;
  const raw = dict[key] ?? fr[key] ?? sharedFallback[key] ?? key;
  return applyTemplate(raw, vars);
}
